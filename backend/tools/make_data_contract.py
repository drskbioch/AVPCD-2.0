"""Writes avpcd_web/DATA_CONTRACT.md from the release database (columns, order) and its data_dictionary table
(kind and first sentence of each description). Nothing is typed by hand for the column lists, so the contract cannot
drift from the release. Run from backend/: python -I tools/make_data_contract.py [path/to/avpcd_v0.1.sqlite3]"""
import re
import sqlite3
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))
from app.config import DEFAULT_DB_PATH  # noqa: E402
from app.queries import SUMMARY_COLUMNS  # noqa: E402

db = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DB_PATH
con = sqlite3.connect(f"{db.resolve().as_uri()}?mode=ro", uri=True)
meta = dict(con.execute("SELECT key, value FROM meta"))
dd = {(t, c): (k, d) for t, c, k, d in con.execute('SELECT "table", "column", kind, description FROM data_dictionary')}


def cols(table):
    return [r[1] for r in con.execute(f'PRAGMA table_info("{table}")')]


def first_sentence(text, limit=170):
    text = re.sub(r"\s+", " ", text.replace("|", "/")).strip()
    m = re.match(r"(.+?[.;])(\s|$)", text)
    out = m.group(1) if m else text
    return out if len(out) <= limit else out[:limit].rsplit(" ", 1)[0] + " ..."


def table_md(table, columns):
    lines = ["| column | kind | description (first sentence of `data_dictionary`) |", "|---|---|---|"]
    for c in columns:
        kind, desc = dd.get((table, c), ("", ""))
        lines.append(f"| `{c}` | {kind} | {first_sentence(desc)} |")
    return "\n".join(lines)


n_rec = con.execute("SELECT COUNT(*) FROM records").fetchone()[0]
rec_cols, paper_cols = cols("records"), cols("papers")
other = [t for (t,) in con.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT IN ('records','papers') ORDER BY name")]

md = f"""# AVPCD API data contract (release {meta['version']}, {meta['date']})

Generated by `backend/tools/make_data_contract.py` from `analysis/phase6/release_v0.1/avpcd_v0.1.sqlite3`. The column lists below are read from that file, so they are exactly the release columns, in release order. The API adds no data field. Status of the data: **{meta['status']}**. {meta['independent_checks'].capitalize()}.

## Rules for every value

- Every column is a **string**, as stored in the release (the SQLite file and the CSV files hold text only). Numbers such as `value_nM`, `value_raw` and `year` are strings in JSON; parse them in the client.
- A missing value is the empty string `""`, never `null`. (`paper` in the record response is `null` when the PMID has no row in `papers`; this does not occur in v0.1.)
- Text is UTF-8. `unit_raw` can contain "µ" (U+00B5), as printed in the paper.
- Curator identifiers are not part of the release and are never returned.
- The release has {n_rec:,} records; the API never returns records outside it.
- `value_nM` is derived by the release (molar units scaled, mass units converted with a looked-up molecular weight); `value_raw`, `unit_raw` and the other recorded columns are as entered by the curators. Filters on `value_nM` therefore leave out records whose `value_nM` is empty.

## Endpoints

All endpoints are `GET`, return JSON (except the CSV download), and report errors as `{{"detail": "..."}}` with status 404 (no such record or table), 403 (downloads disabled) or 422 (invalid parameter).

### `GET /api/records`

Query parameters (all optional; filters combine with AND; several values of one filter combine with OR):

| parameter | meaning |
|---|---|
| `compound` | substring of `compound_name`, case-insensitive for ASCII letters (max 100 characters) |
| `inchikey` | a full InChIKey (27 characters) or its 14-character first block; upper-cased by the server |
| `plant` | substring of `plant_species` or `plant_family` |
| `virus` | substring of `virus_verbatim`, `ictv_species` or `ictv_family` |
| `endpoint` | one or more of the `endpoint` values in the release; repeat the parameter or separate with commas |
| `value_min`, `value_max` | bounds on `value_nM`, in nM, inclusive |
| `tier` | one or more `evidence_tier` values: {', '.join(sorted(set(r[0] for r in con.execute('SELECT DISTINCT evidence_tier FROM records'))))} |
| `flag` | one or more names found in `data_quality_flags`, or `none` for records without a flag |
| `page`, `page_size` | 1-based page; page size default 50, capped at 200 (server setting) |
| `sort`, `order` | `sort` is one of `record_id` (default), `pmid`, `compound_name`, `endpoint`, `evidence_tier`, `value_nM`; `order` is `asc` or `desc`. Empty `value_nM` sorts last in both directions; ties break on `record_id` |

Response:

```json
{{"total": 0, "page": 1, "page_size": 50, "pages": 0, "results": [ /* list items */ ]}}
```

`total`, `page`, `page_size` and `pages` are paging metadata of the API, not release columns.

## List item

The items of `results` carry these {len(SUMMARY_COLUMNS)} columns of the `records` table, in this order:

{table_md('records', SUMMARY_COLUMNS)}

### `GET /api/record/{{record_id}}`

`record_id` looks like `R0002`. Response: `{{"record": {{...}}, "paper": {{...}}}}`. `record` holds **all {len(rec_cols)} columns** of the `records` table; `paper` is the row of the `papers` table with the same `pmid`.

## Record (all columns)

{table_md('records', rec_cols)}

## Paper object

The `papers` table has {len(paper_cols)} columns:

{table_md('papers', paper_cols)}

### `GET /api/stats`

Counts computed from the release at request time (cached while the database file is unchanged):

| field | content |
|---|---|
| `meta` | the `meta` table of the release as an object ({', '.join(f'`{k}`' for k in meta)}) |
| `records`, `papers`, `compounds` | row counts of the tables `records`, `papers`, `compounds` |
| `records_with_structure` | records whose `inchikey` is not empty |
| `by_evidence_tier`, `by_endpoint`, `by_assay_type`, `by_virus_host`, `by_novelty_status` | object: value of that `records` column -> number of records (empty string = records with no value) |
| `by_data_quality_flag` | object: flag name -> number of records carrying it; `none` = records without a flag (a record with two flags counts under both) |

### `GET /api/download`

Disabled unless the server sets `AVPCD_ENABLE_DOWNLOAD=true` (the licence plan of release v0.1 is a proposal and is not confirmed); disabled means status 403. Without `table` it returns `{{"tables": [...], "format": "csv", "usage": "..."}}`. With `table=<name>` it streams that release table as CSV (UTF-8 with byte-order mark, header row = column names, values as stored). Tables of the release: {', '.join(f'`{t}`' for t in ['records', 'papers'] + other)}. Column lists of the tables other than `records` and `papers` are in the release's `data_dictionary.csv`.

### `GET /api/facets/{{kind}}`

`kind` is `virus`, `plant`, `compound` or `endpoint` (otherwise 404). Counts of records for the browse pages, computed from `records`: `{{"kind": "...", "items": [...]}}`. Items are ordered by `records` descending. `records` is an integer; the other fields are strings as stored, with `""` where the release has no value.

| kind | item fields | grouping |
|---|---|---|
| `virus` | `ictv_family`, `ictv_species`, `records` | one item per (`ictv_family`, `ictv_species`) pair, including the empty pair |
| `plant` | `plant_family`, `plant_species`, `records` | one item per (`plant_family`, `plant_species`) pair, including the empty ones |
| `compound` | `inchikey`, `compound_name`, `records` | one item per non-empty `inchikey`; `compound_name` is the most frequent `compound_name` of that key (ties: alphabetical); the release has no compound class column, so there is no browse by class |
| `endpoint` | `endpoint`, `records` | one item per `endpoint` value |

### `GET /api/dictionary`

`{{"rows": [...]}}`: the release table `data_dictionary` as stored. Each row has the strings `table`, `column`, `kind`, `description`, `source`.

### `GET /api/health`

`{{"status": "ok", "release_version": "...", "records": "..."}}` (both values from the `meta` table, as strings). For load balancers; not cached.
"""
out = BACKEND.parent / "DATA_CONTRACT.md"
out.write_text(md, encoding="utf-8", newline="\n")
print(f"wrote {out} ({len(rec_cols)} record columns, {len(paper_cols)} paper columns, {len(SUMMARY_COLUMNS)} list columns)")
